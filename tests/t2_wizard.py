# ---- S2: fault modes
def gen_with(fault):
    r.js(f"WS.S.state.demo.aiFault='{fault}'; WS.S.session.ui.wiz=null")
    r.p.wait_for_timeout(1400); r.go('#/'); r.go('#/soan?ls=ex1-l1-u1-1'); r.p.wait_for_timeout(150)
    r.p.click('[data-a="wzNext"]'); r.p.wait_for_timeout(150)
    r.p.click('[data-a="wzClear"]'); r.p.click('[data-a="wzAdd"]'); r.p.wait_for_timeout(80)
    r.p.select_option('select[data-k="type"][data-i="0"]', 'mcq'); r.p.wait_for_timeout(80)
    r.p.click('[data-a="wzNext"]'); r.p.wait_for_timeout(100); r.p.click('[data-a="wzGen"]')
    r.p.wait_for_function("WS.S.session.gen && Object.values(WS.S.session.gen).filter(g=>g.done).length>=1 && WS.S.session.ui.wiz && WS.S.session.gen[WS.S.session.ui.wiz.wsId] && WS.S.session.gen[WS.S.session.ui.wiz.wsId].done", timeout=20000)
    return r.js("(()=>{const w=WS.S.session.ui.wiz; const g=WS.S.session.gen[w.wsId]; const ws=WS.Q.ws(w.wsId); const ex=WS.Q.ex(ws.items[0].exerciseId); return {status:g.blocks[0].status, log:g.blocks[0].log.join(' | '), done:WS.R.canDone(ex,WS.Q.me(),ws)}})()")
a = gen_with('fixable'); r.check(a['status']=='fixed' and 'Tự sửa vòng 1' in a['log'], f"Lỗi sửa được: tự sửa 1 lần rồi đạt ({a['status']})")
r.shot('t2_fixable')
b = gen_with('hard'); r.check(b['status']=='fail' and not b['done']['ok'] and 'V01' in b['done']['reason'], f"Lỗi cứng: bị chặn Done với lý do rõ ({b['done'].get('reason','')[:90]})")
r.check('Không đạt sau 2 vòng' in b['log'], 'Nhật ký sinh ghi rõ không đạt sau 2 vòng tự sửa')
r.shot('t2_hard')
r.js("WS.S.state.demo.aiFault='off'")
r.done()
